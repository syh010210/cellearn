// 함수명 → 표시용 구문 문자열. 예: syntaxOf("CHOOSE") → "=CHOOSE(숫자, 값1, [값2, ...])"
// 등록되지 않은 함수는 null 을 반환한다.
export function syntaxOf(name) {
  const key = String(name).toUpperCase();
  const args = FUNCTION_ARGS[key];
  if (!args) return null;
  return args.length ? `=${key}(${args.join(", ")})` : `=${key}()`;
}

// 함수명 → 표시용 구문 문자열 맵. FUNCTION_ARGS 에서 파생되므로 따로 관리하지 않는다.
export const FUNCTION_SYNTAX = Object.fromEntries(
  Object.keys(FUNCTION_ARGS).map((n) => [n, syntaxOf(n)]),
);
